class TestLogEvent:
    """log_event passes extra fields through to the record."""

    def test_log_event_with_string_logger(self, caplog: pytest.LogCaptureFixture) -> None:
        with caplog.at_level(logging.INFO, logger="spotify_playlist_manager.test"):
            log_event("spotify_playlist_manager.test", "hello", key="value")
        assert len(caplog.records) == 1
        assert caplog.records[0].getMessage() == "hello"
        assert getattr(caplog.records[0], "key") == "value"

    def test_log_event_with_logger_instance(
        self, caplog: pytest.LogCaptureFixture
    ) -> None:
        logger = logging.getLogger("spotify_playlist_manager.test_inst")
        with caplog.at_level(logging.INFO, logger=logger.name):
            log_event(logger, "event here", count=42)
        assert len(caplog.records) == 1
        assert caplog.records[0].getMessage() == "event here"
        assert getattr(caplog.records[0], "count") == 42


