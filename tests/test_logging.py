class TestSetupLogging:
    """Basic smoke test: setup_logging runs without error and handlers attach."""

    def test_smoke(self, tmp_path: object) -> None:
        from pathlib import Path

        log_file = Path(str(tmp_path)) / "test.log"
        setup_logging(
            level="DEBUG",
            log_file=log_file,
            file_level="DEBUG",
            console=False,
        )
        logger = logging.getLogger("spotify_playlist_manager")
        # Should have exactly one handler (the file handler).
        assert len(logger.handlers) == 1
        # Write something.
        logger.info("smoke test", extra={"foo": "bar"})
        # Flush handlers.
        for h in logger.handlers:
            h.flush()
        # File should contain a JSON line.
        content = log_file.read_text()
        doc = json.loads(content.strip())
        assert doc["event"] == "smoke test"
        assert doc["foo"] == "bar"

    def test_idempotent(self, tmp_path: object) -> None:
        """Calling setup_logging twice doesn't duplicate handlers."""
        from pathlib import Path

        log_file = Path(str(tmp_path)) / "test.log"
        setup_logging(level="INFO", log_file=log_file, console=False)
        setup_logging(level="INFO", log_file=log_file, console=False)
        logger = logging.getLogger("spotify_playlist_manager")
        # Only one file handler (plus maybe NullHandler from __init__).
        file_handlers = [
            h for h in logger.handlers if isinstance(h, logging.handlers.RotatingFileHandler)
        ]
        assert len(file_handlers) == 1
