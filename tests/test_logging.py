class TestStructuredJsonFormatter:
    """JSON formatter produces one JSON line per record with UTC timestamps."""

    def setup_method(self) -> None:
        self.fmt = StructuredJsonFormatter()

    def _emit(self, logger_name: str, msg: str, **extra: object) -> dict:
        record = logging.LogRecord(
            name=logger_name,
            level=logging.INFO,
            pathname="",
            lineno=0,
            msg=msg,
            args=(),
            exc_info=None,
        )
        for k, v in extra.items():
            setattr(record, k, v)
        line = self.fmt.format(record)
        return json.loads(line)

    def test_basic_fields(self) -> None:
        doc = self._emit("spotify_playlist_manager.api", "GET /v1/me")
        assert doc["level"] == "INFO"
        assert doc["logger"] == "spotify_playlist_manager.api"
        assert doc["event"] == "GET /v1/me"
        assert doc["timestamp"].endswith("Z")

    def test_custom_extra_fields(self) -> None:
        doc = self._emit(
            "spotify_playlist_manager.user",
            "tracks.add",
            playlist_id="abc123",
            track_count=5,
        )
        assert doc["playlist_id"] == "abc123"
        assert doc["track_count"] == 5

    def test_exception_included(self) -> None:
        try:
            raise ValueError("bad input")
        except ValueError:
            exc_info = sys.exc_info()

        record = logging.LogRecord(
            name="spm",
            level=logging.ERROR,
            pathname="",
            lineno=0,
            msg="something broke",
            args=(),
            exc_info=exc_info,
        )
        line = self.fmt.format(record)
        doc = json.loads(line)
        assert doc["exception"]["type"] == "ValueError"
        assert doc["exception"]["message"] == "bad input"
        assert "traceback" in doc["exception"]

    def test_non_serialisable_value_coerced(self) -> None:
        class Custom:
            def __str__(self) -> str:
                return "custom_obj"

        doc = self._emit("spm", "test", custom=Custom())
        assert doc["custom"] == "custom_obj"

    def test_list_and_dict_fields(self) -> None:
        doc = self._emit(
            "spm",
            "test",
            uris=["spotify:track:aaa", "spotify:track:bbb"],
            meta={"key": "value"},
        )
        assert doc["uris"] == ["spotify:track:aaa", "spotify:track:bbb"]
        assert doc["meta"] == {"key": "value"}


