class TestHumanReadableFormatter:
    """Human-readable formatter for stderr console output."""

    def setup_method(self) -> None:
        self.fmt = HumanReadableFormatter()

    def test_basic_format(self) -> None:
        record = logging.LogRecord(
            name="spotify_playlist_manager.api",
            level=logging.WARNING,
            pathname="",
            lineno=0,
            msg="rate limited",
            args=(),
            exc_info=None,
        )
        line = self.fmt.format(record)
        assert "WARNING" in line
        assert "spm.api" in line
        assert "rate limited" in line
        # Timestamp in HH:MM:SS format.
        assert "[" in line and "]" in line

    def test_exception_appended_short(self) -> None:
        try:
            raise RuntimeError("boom")
        except RuntimeError:
            exc_info = sys.exc_info()

        record = logging.LogRecord(
            name="spotify_playlist_manager",
            level=logging.ERROR,
            pathname="",
            lineno=0,
            msg="failed",
            args=(),
            exc_info=exc_info,
        )
        line = self.fmt.format(record)
        assert "RuntimeError" in line
        assert "boom" in line


