# RedactionFilter
# ---------------------------------------------------------------------------


class TestRedactionFilter:
    """Mask secrets in messages, exc_text, stack_info, and extra fields."""

    def setup_method(self) -> None:
        self.filt = RedactionFilter()

    def _make_record(
        self,
        msg: str,
        *,
        exc_info: tuple | None = None,
        extra: dict | None = None,
    ) -> logging.LogRecord:
        record = logging.LogRecord(
            name="spm.test",
            level=logging.INFO,
            pathname="",
            lineno=0,
            msg=msg,
            args=(),
            exc_info=exc_info,
        )
        if extra:
            for k, v in extra.items():
                setattr(record, k, v)
        return record

    # -- password in message --

    def test_masks_password_in_message(self) -> None:
        rec = self._make_record("librespot started --password hunter2 --name kitchen")
        self.filt.filter(rec)
        assert "hunter2" not in rec.msg
        assert "[REDACTED]" in rec.msg

    def test_masks_client_secret(self) -> None:
        rec = self._make_record("client_secret=abc123def456")
        self.filt.filter(rec)
        assert "abc123def456" not in rec.msg
        assert "[REDACTED]" in rec.msg

    def test_masks_access_token(self) -> None:
        rec = self._make_record("access_token: Bearer eyJhbGciOiJIUzI1NiJ9.test.signature")
        self.filt.filter(rec)
        assert "eyJhbGci" not in rec.msg
        assert "[REDACTED]" in rec.msg

    def test_masks_bearer_token(self) -> None:
        rec = self._make_record("Authorization: Bearer BQDj1234567890abcdef")
        self.filt.filter(rec)
        assert "BQDj1234567890" not in rec.msg
        assert "[REDACTED]" in rec.msg

    # -- password in extra fields (list of args, like a subprocess argv) --

    def test_masks_password_in_extra_fields_list(self) -> None:
        """List extra fields with --password + value pairs are redacted."""
        rec = self._make_record(
            "device started",
            extra={"cmd": ["librespot", "--password", "s3cret", "--name", "kitchen"]},
        )
        self.filt.filter(rec)
        cmd = getattr(rec, "cmd")
        assert cmd == ["librespot", "--password", "[REDACTED]", "--name", "kitchen"]
        assert "s3cret" not in str(cmd)

    def test_masks_password_in_extra_fields_string(self) -> None:
        """String extra fields with --password + value are redacted."""
        rec = self._make_record(
            "device started",
            extra={"cmd_str": "librespot --password s3cret --name kitchen"},
        )
        self.filt.filter(rec)
        assert "s3cret" not in getattr(rec, "cmd_str", "")

    # -- exc_info / traceback redaction --

    def test_masks_secret_in_exception_message(self) -> None:
        try:
            raise ValueError("token Bearer abcdef123456abcdef123456abcdef123456 failed")
        except ValueError:
            exc_info = sys.exc_info()

        rec = self._make_record("auth failed", exc_info=exc_info)
        self.filt.filter(rec)

        # exc_text is generated by the filter from exc_info, then redacted.
        assert rec.exc_text is not None
        assert "abcdef123456" not in rec.exc_text
        assert "[REDACTED]" in rec.exc_text

    def test_masks_secret_in_message_with_exc_info(self) -> None:
        """Redaction also applies to the main message when exc_info is present."""
        try:
            raise RuntimeError("something broke")
        except RuntimeError:
            exc_info = sys.exc_info()

        rec = self._make_record(
            "client_secret=supersecret12345678 failed",
            exc_info=exc_info,
        )
        self.filt.filter(rec)
        assert "supersecret12345678" not in rec.msg
        assert "[REDACTED]" in rec.msg

    # -- argv masking --

    def test_redact_argv_masks_password_value(self) -> None:
        argv = ["librespot", "--name", "kitchen", "--password", "mysecret", "-v"]
        result = RedactionFilter.redact_argv(argv)
        assert result == ["librespot", "--name", "kitchen", "--password", "[REDACTED]", "-v"]
        assert "mysecret" not in " ".join(result)

    def test_redact_argv_no_password(self) -> None:
        argv = ["librespot", "--name", "kitchen", "--backend", "pulseaudio"]
        result = RedactionFilter.redact_argv(argv)
        assert result == argv

    def test_redact_argv_empty(self) -> None:
        assert RedactionFilter.redact_argv([]) == []


